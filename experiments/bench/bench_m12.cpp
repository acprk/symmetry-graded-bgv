// ===========================================================================
// bench_m12 -- stage-level digit-extraction harness, generation 1.
//
// Scope: Gaussian box (`sup=box`, radix of order 4) and Eisenstein hexagon
// (`sup=hex`, radix of order 6); scalar axis only, no composed (r,d) arm.
//
// Produced in the paper:
//   results/raw_logs/sweep_aligned65537.log   (run_aligned65537.sh)
//   -- the order-4/2/1 scalar axis on Ma et al.'s own ring p=65537, m=50731,
//      quoted in the text but not itself a table row.
//
// The `RESULT  kappa  time_s  mults  cap_used verify` header and its rows are
// what Tables 12 and 13 of the paper are read out of; see ../README.md.
// ===========================================================================
// M12: order-SIX (Eisenstein) character filter, measured on the real digit-extraction
// polynomial, against the r=3, r=2 and generic r=1 baselines on the SAME support.
//
// Radix A has multiplicative order 6 with A^2 = A - 1 (a primitive 6th root of unity,
// available iff p = 1 mod 3).  The support is the Eisenstein hexagon
//        T_B = { (eta,lambda) : |eta|,|lambda|,|eta+lambda| <= B },   x = eta*A + lambda,
// which is stable under x -> A*x, since (eta,lambda) -> (eta+lambda, -eta).
// The digit map is lambda(x) = lambda (the second coordinate).
//
// For a filter of order r | 6 we use the subgroup generated by Atil = A^(6/r) and write
//        P_A(x) = c1 * x + x^(r-1) * Q(x^r),      c1 = 1/(1 - Atil^2)   (c1 = 0 if r = 2),
// which is exactly the unified order-r functional equation P_A(Ax) = A^{-1}(P_A(x) - x).
// r = 1 is the generic baseline: P interpolated on all of S_A and evaluated by BSGS.
//
// Every configuration is verified by decryption against the true low digit.
#include <helib/helib.h>
#include <helib/ArgMap.h>
#include <NTL/BasicThreadPool.h>
#include <NTL/ZZ_pX.h>
#include <chrono>
#include <cstdio>
#include <cstdlib>
#include <map>
#include <set>
#include <sstream>
#include <string>
#include <vector>
using namespace helib;
using namespace std;

static double now_s() {
  using namespace std::chrono;
  return duration<double>(steady_clock::now().time_since_epoch()).count();
}
static long MULTS = 0;
static void mulCt(Ctxt& a, const Ctxt& b) { a.multiplyBy(b); MULTS++; }
static void sqCt(Ctxt& a) { a.square(); a.reLinearize(); MULTS++; }

static vector<Ctxt> babySteps(const Ctxt& x, long kappa) {
  vector<Ctxt> b;
  b.push_back(Ctxt(x.getPubKey(), x.getPtxtSpace()));
  b.push_back(x);
  for (long i = 2; i <= kappa; i++) {
    long h = i / 2; Ctxt t = b[h];
    if (i - h == h) sqCt(t); else mulCt(t, b[i - h]);
    b.push_back(t);
  }
  return b;
}

static Ctxt bsgs(const Ctxt& x, const vector<NTL::ZZX>& co, long kappa) {
  long k = (long)co.size() - 1;
  if (kappa > k + 1) kappa = k + 1;
  if (kappa < 1) kappa = 1;
  vector<Ctxt> baby = babySteps(x, kappa);
  long nb = (k + 1 + kappa - 1) / kappa;
  auto block = [&](long blk) {
    Ctxt part(x.getPubKey(), x.getPtxtSpace()); part.clear(); bool e = true;
    for (long i = 0; i < kappa; i++) {
      long idx = blk * kappa + i; if (idx > k) break;
      Ctxt t(x.getPubKey(), x.getPtxtSpace());
      if (i == 0) { t.clear(); t.addConstant(co[idx]); }
      else { t = baby[i]; t.multByConstant(co[idx]); }
      if (e) { part = t; e = false; } else part += t;
    }
    return part;
  };
  Ctxt acc = block(nb - 1);
  for (long blk = nb - 2; blk >= 0; blk--) { mulCt(acc, baby[kappa]); acc += block(blk); }
  return acc;
}

int main(int argc, char** argv) {
  string kaps = "4,6,8,10,12,14,16,20";
  string sup = "hex";   // hex = Eisenstein hexagon (A order 6, r in {1,2,3,6})
                        // box = Gaussian square    (A order 4, r in {1,2,4})
  long m = 60697, p = 4003, A = 823, B = 20, bits = 900, ordr = 6, kappa = 0, reps = 1, nt = 1;
  ArgMap().arg("m", m).arg("p", p).arg("A", A).arg("B", B).arg("bits", bits)
      .arg("ordr", ordr).arg("kappa", kappa).arg("kaps", kaps).arg("reps", reps)
      .arg("sup", sup).arg("threads", nt).parse(argc, argv);
  NTL::SetNumThreads(nt);
  bool hex = (sup == "hex");
  // Any 1 <= ordr <= 32 is accepted; for orders whose filter does not exist the
  // run terminates at the structural (orbit-consistency) check with FATAL,
  // which is the measured verdict for that order.
  if (ordr < 1 || ordr > 32) {
    fprintf(stderr, "ordr must be in 1..32\n"); return 1; }

  // ---- radix sanity ----
  // hex: A must be a primitive 6th root of unity, A^2 = A - 1  (Eisenstein unit)
  // box: A must be a primitive 4th root of unity, A^2 = -1     (Gaussian unit)
  if (hex) {
    if (NTL::PowerMod(A % p, 6, p) != 1 || NTL::PowerMod(A % p, 3, p) == 1 ||
        NTL::PowerMod(A % p, 2, p) == 1 || (((A % p) * (A % p) - (A % p) + 1) % p) != 0) {
      fprintf(stderr, "A=%ld is not a primitive 6th root of unity mod p=%ld\n", A, p); return 1; }
  } else {
    if (NTL::PowerMod(A % p, 4, p) != 1 || NTL::PowerMod(A % p, 2, p) == 1 ||
        ((NTL::MulMod(A % p, A % p, p) + 1) % p) != 0) {
      fprintf(stderr, "A=%ld is not a primitive 4th root of unity mod p=%ld\n", A, p); return 1; }
  }

  double t0 = now_s();
  Context context = ContextBuilder<BGV>().m(m).p(p).r(1).bits(bits).c(3).build();
  SecKey sk(context); sk.GenSecKey(); addFrbMatrices(sk);
  const PubKey& pk = sk;
  const EncryptedArray& ea = context.getEA();
  long d = context.getOrdP(), nslots = ea.size();
  printf("context m=%ld p=%ld d=%ld nslots=%ld  filter r=%ld  A=%ld  B=%ld  setup=%.1fs\n",
         m, p, d, nslots, ordr, A, B, now_s() - t0);
  fflush(stdout);

  NTL::ZZ pZZ = NTL::conv<NTL::ZZ>(p);
  NTL::ZZ_pPush push(pZZ);
  long fullOrd = hex ? 6 : 4;
  long Atil = (ordr >= 2 && fullOrd % ordr == 0)
                  ? NTL::PowerMod(A % p, fullOrd / ordr, p) : 0;

  // ---- support: A-stability and injectivity ----
  // hex: T_B = {(h,l): |h|,|l|,|h+l| <= B},  x -> Ax  is  (h,l) -> (h+l,-h)
  // box: T_B = {(h,l): |h|,|l| <= B},        x -> Ax  is  (h,l) -> (l,-h)
  vector<pair<long,long>> hexc;
  for (long h = -B; h <= B; h++)
    for (long l = -B; l <= B; l++)
      if (!hex || labs(h + l) <= B) hexc.push_back(make_pair(h, l));
  set<pair<long,long> > hexset(hexc.begin(), hexc.end());
  for (size_t i = 0; i < hexc.size(); i++) {
    pair<long,long> img = hex
        ? make_pair(hexc[i].first + hexc[i].second, -hexc[i].first)
        : make_pair(hexc[i].second, -hexc[i].first);
    if (!hexset.count(img)) {
      printf("FATAL: support not A-stable at (%ld,%ld)\n", hexc[i].first, hexc[i].second);
      return 1; }
  }
  map<long,long> lamOf;
  vector<pair<long,long> > testIn;
  for (size_t i = 0; i < hexc.size(); i++) {
    long h = hexc[i].first, l = hexc[i].second;
    long x = (((( h % p) * (A % p)) % p + l) % p + p) % p;
    long lv = ((l % p) + p) % p;
    map<long,long>::iterator it = lamOf.find(x);
    if (it != lamOf.end() && it->second != lv) {
      printf("FATAL: support not injective at x=%ld\n", x); return 1; }
    lamOf[x] = lv; testIn.push_back(make_pair(x, lv));
  }
  long Ssize = (long)lamOf.size();
  if (Ssize != (long)hexc.size()) {
    printf("FATAL: |S|=%ld != support size %ld (collision)\n", Ssize, (long)hexc.size());
    return 1; }
  printf("%s B=%ld |S_A|=%ld (formula=%ld) A-stable injective\n",
         hex ? "hexagon" : "box", B, Ssize,
         hex ? 3*B*B + 3*B + 1 : (2*B+1)*(2*B+1));

  // ---- build the polynomial actually evaluated ----
  long c1 = 0, u = 0, n = 0;
  NTL::ZZ_pX Poly;
  if (ordr == 1) {
    n = Ssize;
    NTL::vec_ZZ_p xv, yv; xv.SetLength(Ssize); yv.SetLength(Ssize);
    long i = 0;
    for (map<long,long>::iterator it = lamOf.begin(); it != lamOf.end(); ++it) {
      xv[i] = NTL::conv<NTL::ZZ_p>(it->first);
      yv[i] = NTL::conv<NTL::ZZ_p>(it->second); i++; }
    Poly = NTL::interpolate(xv, yv);
    printf("generic baseline: deg P = %ld (no filter)\n", (long)NTL::deg(Poly));
  } else {
    u = ordr - 1;
    // The digit map is covariant under the FULL order-6 generator A, so the linear
    // coefficient c1 = 1/(1 - A^2) is intrinsic to the digit map and is inherited by
    // every sub-filter: the order-6 form X^5 Q6(X^6) = X^2 * [X^3 Q6(X^6)] is already
    // of the order-3 form X^2 R(X^3) with the SAME c1.  Recomputing c1 from the
    // subgroup generator Atil is wrong and makes the order-3 ansatz fail to close.
    // For r = 2 the ansatz is X*(c1 + Q(X^2)), which absorbs c1, so we take c1 = 0
    // to recover exactly the odd-polynomial baseline of Ma et al.
    long A2 = NTL::MulMod(A % p, A % p, p);
    long den = ((1 - A2) % p + p) % p;
    c1 = (ordr >= 3 && den != 0) ? NTL::InvMod(den, p) : 0;
    map<long,long> qval;
    for (map<long,long>::iterator it = lamOf.begin(); it != lamOf.end(); ++it) {
      long x = it->first, lv = it->second;
      if (x == 0) continue;
      long y = NTL::PowerMod(x, ordr, p);
      long t = NTL::SubMod(lv, NTL::MulMod(x, c1, p), p);
      long v = NTL::MulMod(t, NTL::InvMod(NTL::PowerMod(x, u, p), p), p);
      map<long,long>::iterator jt = qval.find(y);
      if (jt == qval.end()) qval[y] = v;
      else if (jt->second != v) {
        printf("FATAL: order-%ld structure violated at x=%ld (Atil=%ld c1=%ld)\n",
               ordr, x, Atil, c1);
        return 1; }
    }
    n = (long)qval.size();
    printf("order-%ld filter: Atil=%ld c1=%ld n=|orbits|=%ld degQ=%ld density=1/%ld\n",
           ordr, Atil, c1, n, n - 1, ordr);
    NTL::vec_ZZ_p xq, yq; xq.SetLength(n); yq.SetLength(n);
    long i = 0;
    for (map<long,long>::iterator it = qval.begin(); it != qval.end(); ++it) {
      xq[i] = NTL::conv<NTL::ZZ_p>(it->first);
      yq[i] = NTL::conv<NTL::ZZ_p>(it->second); i++; }
    Poly = NTL::interpolate(xq, yq);
  }
  fflush(stdout);

  vector<NTL::ZZX> co;
  for (long i = 0; i <= NTL::deg(Poly); i++) {
    NTL::ZZX cz; NTL::conv(cz, NTL::rep(NTL::coeff(Poly, i)));
    vector<NTL::ZZX> sv(nslots, cz); NTL::ZZX e; ea.encode(e, sv); co.push_back(e);
  }

  vector<long> lam(nslots);
  Ptxt<BGV> ptx(context);
  for (long i = 0; i < nslots; i++) {
    pair<long,long>& pr = testIn[i % testIn.size()];
    ptx[i] = NTL::ZZX(pr.first); lam[i] = pr.second;
  }
  Ctxt base(pk); pk.Encrypt(base, ptx);

  vector<long> kapList;
  { stringstream ss(kaps); string tok;
    while (getline(ss, tok, ',')) if (!tok.empty()) kapList.push_back(atol(tok.c_str())); }
  if (kappa > 0) { kapList.clear(); kapList.push_back(kappa); }

  printf("\nRESULT r=%ld degEval=%ld |S|=%ld\n", ordr, (long)NTL::deg(Poly), Ssize);
  printf("RESULT %6s %9s %7s %9s %s\n", "kappa", "time_s", "mults", "cap_used", "verify");
  for (size_t ki = 0; ki < kapList.size(); ki++) {
    long kap = kapList[ki];
    for (long rep = 0; rep < reps; rep++) {
      MULTS = 0; double s0 = now_s();
      long c0 = base.bitCapacity();
      Ctxt res(pk);
      if (ordr == 1) {
        res = bsgs(base, co, kap);
      } else {
        // powers: x^2, x^3, x^5, x^6 as needed
        Ctxt x2 = base; sqCt(x2);
        Ctxt xr(pk), xu(pk);
        if (ordr == 2)      { xr = x2;                       xu = base; }
        else if (ordr == 3) { Ctxt x3 = x2; mulCt(x3, base); xr = x3;  xu = x2; }
        else if (ordr == 4) { Ctxt x3 = x2; mulCt(x3, base);
                              Ctxt x4 = x2; sqCt(x4);
                              xr = x4; xu = x3; }
        else if (ordr == 6) { Ctxt x3 = x2; mulCt(x3, base);
                              Ctxt x6 = x3; sqCt(x6);
                              Ctxt x5 = x3; mulCt(x5, x2);
                              xr = x6; xu = x5; }
        else                { // generic ladder (reached only if some order
                              // outside {2,3,4,6} ever closed structurally)
                              xu = base;
                              for (long e = 2; e <= ordr - 1; e++) mulCt(xu, base);
                              xr = xu; mulCt(xr, base); }
        Ctxt Qv = bsgs(xr, co, kap);
        res = Qv; mulCt(res, xu);
        if (c1) { Ctxt lin = base; lin.multByConstant(NTL::to_ZZ(c1)); res += lin; }
      }
      long capEnd = res.bitCapacity();
      double el = now_s() - s0;
      vector<NTL::ZZX> out; ea.decrypt(res, sk, out);
      long bad = 0;
      for (long i = 0; i < nslots; i++) {
        if (NTL::deg(out[i]) > 0) { bad++; continue; }
        long got = ((NTL::conv<long>(NTL::coeff(out[i], 0)) % p) + p) % p;
        if (got != lam[i]) bad++;
      }
      printf("RESULT %6ld %9.3f %7ld %9ld %s\n", kap, el, MULTS, c0 - capEnd,
             bad == 0 ? "CORRECT" : "WRONG");
      fflush(stdout);
    }
  }
  printf("=== m12 done ===\n");
  return 0;
}
